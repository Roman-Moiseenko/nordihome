    /**
     * Получить имя поля AvitoProductEntity по названию колонки шаблона.
     */
    public static function fieldByLabel(string $label): ?string
    {
        return self::MAP[$label] ?? null;
    }

    /**
     * Получить название колонки шаблона по имени поля AvitoProductEntity.
     */
    public static function labelByField(string $field): ?string
    {
        $flipped = array_flip(self::MAP);

        return $flipped[$field] ?? null;
    }

    /**
     * Является ли колонка общим полем AvitoProduct (не параметром категории).
     */
    public static function isMappedLabel(string $label): bool
    {
        return array_key_exists($label, self::MAP);
    }

    /**
     * Нужно ли пропустить колонку (нет поля в сущности и не параметр категории).
     */
    public static function shouldSkip(string $label): bool
    {
        return in_array($label, self::SKIP, true);
    }

    /**
     * @return array<string, string> label => field
     */
    public static function all(): array
    {
        return self::MAP;
    }
}
